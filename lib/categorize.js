// کلاس «حرف» برای مرزبندی کلمه. جاوااسکریپت \b را روی فارسی درست تشخیص نمی‌دهد،
// پس مرز را دستی می‌سازیم. فقط ابتدای کلمه مرز می‌خواهد نه انتهایش، تا پسوندهای
// فارسی («بازارها»، «دلاری») همچنان تطبیق کنند ولی «ارز» داخل «آلوارز» تطبیق نکند.
const LETTER = '\\u0600-\\u06FF\\u200cA-Za-z0-9';

const COMPILED = RULES.map(([cat, words]) => [
  cat,
  WEIGHT[cat] || 1,
  words.map(w => new RegExp(`(?<![${LETTER}])(?:${w})`, 'i')),
]);

/**
 * دسته یک کلیدواژه را برمی‌گرداند، یا null اگر هیچ قاعده‌ای مطابقت نکرد.
 * امتیاز = تعداد تطبیق‌ها (وزن ۱۰) + اختصاصی‌بودن دسته، تا هم کلیدواژه‌های
 * چندبخشی درست دسته‌بندی شوند و هم تساوی‌ها به نفع دسته‌ی دقیق‌تر حل شود.
 */
function categorizeKeyword(keyword) {
  // نیم‌فاصله را فاصله حساب کن تا مرز کلمه درست کار کند
  const kw = String(keyword || '').replace(/‌/g, ' ').trim();
  if (!kw) return null;
  let best = null, bestScore = 0;
  for (const [cat, weight, regexes] of COMPILED) {
    let hits = 0;
    for (const re of regexes) if (re.test(kw)) hits++;
    if (!hits) continue;
    const score = hits * 10 + weight;
    if (score > bestScore) { bestScore = score; best = cat; }
  }
  return best;
}

module.exports = { categorizeKeyword, CATEGORIES };
